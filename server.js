import http from "node:http";
import { readFile } from "node:fs/promises";
import { extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL(".", import.meta.url));
const PUBLIC_DIR = join(ROOT, "public");
const PORT = Number(process.env.PORT || 3000);
const MAX_BODY_BYTES = 32 * 1024;
const MAX_MESSAGE_CHARS = 8000;
const MAX_HISTORY_ITEMS = 12;
const MIME = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon"
};

function json(res, status, payload) {
  res.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "cache-control": "no-store",
    "x-content-type-options": "nosniff"
  });
  res.end(JSON.stringify(payload));
}

async function readJson(req) {
  let size = 0;
  const chunks = [];
  for await (const chunk of req) {
    size += chunk.length;
    if (size > MAX_BODY_BYTES) {
      const error = new Error("Request body is too large.");
      error.status = 413;
      throw error;
    }
    chunks.push(chunk);
  }
  try {
    return JSON.parse(Buffer.concat(chunks).toString("utf8"));
  } catch {
    const error = new Error("Request body must be valid JSON.");
    error.status = 400;
    throw error;
  }
}

function starterReply(message) {
  const text = message.trim();
  if (/^(hi|hello|hey)\b/i.test(text)) {
    return "Hello! I'm Dream AI. My core service is running. Connect an AI model provider to enable full open-ended reasoning.";
  }
  if (/who are you|what are you/i.test(text)) {
    return "I'm Dream AI, an independent AI assistant project. This starter build includes the chat interface, API, safety limits and a provider adapter. A language model can be connected through environment settings.";
  }
  return "I received your message. Dream AI's application and API are working, but no language model is connected yet. Add an OpenAI-compatible provider in the deployment environment (AI_BASE_URL, AI_API_KEY and AI_MODEL) to enable full AI responses. This starter response is not generated by a trained language model.";
}

async function getModelReply(messages) {
  const { AI_BASE_URL, AI_API_KEY, AI_MODEL } = process.env;
  if (!AI_BASE_URL || !AI_API_KEY || !AI_MODEL) {
    return { reply: starterReply(messages.at(-1).content), mode: "starter" };
  }

  let endpoint;
  try {
    endpoint = new URL(AI_BASE_URL);
  } catch {
    throw new Error("AI_BASE_URL must be a valid URL.");
  }
  if (!["https:", "http:"].includes(endpoint.protocol)) {
    throw new Error("AI_BASE_URL must use HTTP or HTTPS.");
  }

  const base = AI_BASE_URL.replace(/\/+$/, "");
  const url = base.endsWith("/chat/completions")
    ? base
    : `${base}/chat/completions`;
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 45000);
  try {
    const response = await fetch(url, {
      method: "POST",
      headers: {
        "content-type": "application/json",
        authorization: `Bearer ${AI_API_KEY}`
      },
      body: JSON.stringify({
        model: AI_MODEL,
        messages: [
          {
            role: "system",
            content: "You are Dream AI, a helpful, honest and clear AI assistant. Do not claim to have performed actions you have not performed."
          },
          ...messages
        ],
        temperature: 0.7
      }),
      signal: controller.signal
    });
    if (!response.ok) {
      const detail = (await response.text()).slice(0, 500);
      console.error("Model provider returned", response.status, detail);
      throw new Error("The configured AI provider could not complete the request.");
    }
    const data = await response.json();
    const reply = data?.choices?.[0]?.message?.content;
    if (typeof reply !== "string" || !reply.trim()) {
      throw new Error("The AI provider returned an empty response.");
    }
    return { reply: reply.trim(), mode: "connected" };
  } catch (error) {
    if (error.name === "AbortError") {
      throw new Error("The AI provider took too long to respond. Please try again.");
    }
    throw error;
  } finally {
    clearTimeout(timeout);
  }
}

async function handleChat(req, res) {
  const body = await readJson(req);
  if (!Array.isArray(body.messages) || body.messages.length === 0) {
    return json(res, 400, { error: "Send a non-empty messages array." });
  }
  const messages = body.messages.slice(-MAX_HISTORY_ITEMS);
  for (const item of messages) {
    if (
      !item ||
      !["user", "assistant"].includes(item.role) ||
      typeof item.content !== "string" ||
      !item.content.trim() ||
      item.content.length > MAX_MESSAGE_CHARS
    ) {
      return json(res, 400, {
        error: "Each message needs a valid user/assistant role and text under 8,000 characters."
      });
    }
  }
  if (messages.at(-1).role !== "user") {
    return json(res, 400, { error: "The last message must be from the user." });
  }

  try {
    const result = await getModelReply(messages);
    return json(res, 200, result);
  } catch (error) {
    console.error("Chat request failed:", error.message);
    return json(res, 502, { error: error.message || "AI service unavailable." });
  }
}

async function serveStatic(encodedPathname, res) {
  let pathname;
  try {
    pathname = decodeURIComponent(encodedPathname);
  } catch {
    res.writeHead(400, { "content-type": "text/plain; charset=utf-8" });
    res.end("Invalid URL path");
    return;
  }
  const requested = pathname === "/" ? "/index.html" : pathname;
  const filePath = resolve(PUBLIC_DIR, "." + requested);
  const pathFromPublic = relative(PUBLIC_DIR, filePath);
  if (
    pathFromPublic === ".." ||
    pathFromPublic.startsWith(".." + sep) ||
    resolve(filePath) === resolve(PUBLIC_DIR)
  ) {
    res.writeHead(403, { "content-type": "text/plain; charset=utf-8" });
    res.end("Forbidden");
    return;
  }
  try {
    const content = await readFile(filePath);
    res.writeHead(200, {
      "content-type": MIME[extname(filePath)] || "application/octet-stream",
      "x-content-type-options": "nosniff",
      "referrer-policy": "strict-origin-when-cross-origin"
    });
    res.end(content);
  } catch {
    res.writeHead(404, { "content-type": "text/plain; charset=utf-8" });
    res.end("Not found");
  }
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host || "localhost"}`);
  if (req.method === "GET" && url.pathname === "/api/health") {
    return json(res, 200, {
      ok: true,
      name: "Dream AI",
      version: "0.1.0",
      modelConnected: Boolean(process.env.AI_BASE_URL && process.env.AI_API_KEY && process.env.AI_MODEL)
    });
  }
  if (req.method === "POST" && url.pathname === "/api/chat") {
    try {
      return await handleChat(req, res);
    } catch (error) {
      return json(res, error.status || 500, {
        error: error.status ? error.message : "An unexpected server error occurred."
      });
    }
  }
  if (req.method === "GET") return serveStatic(url.pathname, res);
  res.writeHead(405, { allow: "GET, POST" }).end("Method not allowed");
});

server.listen(PORT, "0.0.0.0", () => {
  console.log(`Dream AI listening on port ${PORT}`);
});

function shutdown() {
  server.close(() => process.exit(0));
}
process.on("SIGTERM", shutdown);
process.on("SIGINT", shutdown);
