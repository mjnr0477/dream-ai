#!/usr/bin/env bash
set -euo pipefail

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

if [[ "${EUID}" -ne 0 ]]; then
  die "Run as root: sudo bash scripts/enable-dream-native-inference-worker.sh"
fi
[[ -r /etc/dream-ai/notebook-worker.env ]] || die "Install the persistent DREAM notebook worker first."
[[ -x /opt/dream-ai/.venv/bin/python ]] || die "DREAM's persistent GPU worker environment is not installed."
[[ -f /etc/systemd/system/dream-native-inference-worker.service ]] || die "Native inference systemd unit is missing."
[[ -t 0 ]] || die "Run interactively so the approved checkpoint hash can be entered."

# This is the root-owned, mode-0600 file generated by the DREAM installer.
set -a
. /etc/dream-ai/notebook-worker.env
set +a

[[ "${DREAM_HOST_WORKER_TOKEN:-}" =~ ^[A-Za-z0-9._+=/-]{32,}$ ]] || die "DREAM_HOST_WORKER_TOKEN is missing; reinstall/update the worker config first."
[[ "${DREAM_HOST_ARTIFACT_TOKEN:-}" =~ ^[A-Za-z0-9._+=/-]{32,}$ ]] || die "DREAM_HOST_ARTIFACT_TOKEN is missing; reinstall/update the worker config first."

printf 'This activates native inference only after a reviewed SFT checkpoint passed DREAM evaluation.\n'
printf 'Before continuing, set these values on dream-host-live and wait for its deployment:\n'
printf '  DREAM_HOST_MODEL_NAME=dream-native-v1\n'
printf '  DREAM_HOST_ADAPTER_NAME=none\n'
read -r -p "Enter the approved SHA-256 of dream-native-sft-checkpoint.pt: " APPROVED_SHA
APPROVED_SHA="${APPROVED_SHA,,}"
[[ "${APPROVED_SHA}" =~ ^[a-f0-9]{64}$ ]] || die "The approved checkpoint SHA-256 must contain exactly 64 hexadecimal characters."

export DREAM_APPROVED_SHA256="${APPROVED_SHA}"
/opt/dream-ai/.venv/bin/python - <<'PY'
import os
import requests

host = os.environ.get("DREAM_HOST_URL", "https://dream-host-live.onrender.com").rstrip("/")
artifact_token = os.environ["DREAM_HOST_ARTIFACT_TOKEN"]
expected_sha = os.environ["DREAM_APPROVED_SHA256"]
expected_model = "dream-native-v1"
expected_adapter = "none"

health = requests.get(host + "/health", timeout=30)
health.raise_for_status()
status = health.json()
if status.get("model") != expected_model or status.get("adapter") != expected_adapter:
    raise SystemExit(
        "DREAM HOST is not configured for native inference yet. "
        "Set DREAM_HOST_MODEL_NAME=dream-native-v1 and DREAM_HOST_ADAPTER_NAME=none, deploy, then rerun."
    )

response = requests.get(
    host + "/api/v1/notebook/artifacts",
    headers={"Authorization": "Bearer " + artifact_token},
    timeout=30,
)
response.raise_for_status()
artifacts = response.json().get("artifacts", [])
matches = [
    item for item in artifacts
    if item.get("name") == "dream-native-sft-checkpoint.pt"
    and item.get("sha256") == expected_sha
]
if len(matches) != 1:
    raise SystemExit("The exact approved SFT checkpoint hash is not present in the existing DREAM R2 vault.")
size = matches[0].get("size_bytes")
if not isinstance(size, int) or not 1 <= size <= 128 * 1024 * 1024:
    raise SystemExit("The native checkpoint exceeds the supported inference checkpoint size.")
print("R2 release artifact verified:", matches[0]["name"], "bytes:", size, "sha256:", expected_sha)
print("DREAM HOST model configuration verified:", status["model"], "adapter:", status["adapter"])
PY

install -d -o dreamai -g dreamai -m 0700 /var/lib/dream-ai/models
install -d -m 0700 /etc/dream-ai
umask 077
cat > /etc/dream-ai/native-inference-worker.env <<EOF
DREAM_HOST_URL=https://dream-host-live.onrender.com
DREAM_HOST_WORKER_TOKEN=${DREAM_HOST_WORKER_TOKEN}
DREAM_HOST_ARTIFACT_TOKEN=${DREAM_HOST_ARTIFACT_TOKEN}
DREAM_HOST_MODEL_NAME=dream-native-v1
DREAM_HOST_ADAPTER_NAME=none
DREAM_NATIVE_CHECKPOINT_ARTIFACT=dream-native-sft-checkpoint.pt
DREAM_NATIVE_CHECKPOINT_SHA256=${APPROVED_SHA}
DREAM_NATIVE_CHECKPOINT_PATH=/var/lib/dream-ai/models/dream-native-instruct.pt
DREAM_HOST_WORKER_POLL_SECONDS=1.5
EOF
chmod 0600 /etc/dream-ai/native-inference-worker.env
unset APPROVED_SHA DREAM_APPROVED_SHA256

systemctl daemon-reload
systemctl enable --now dream-native-inference-worker.service

printf '\nNative DREAM inference worker enabled.\n'
systemctl --no-pager --full status dream-native-inference-worker.service || true
printf '\nLogs: journalctl -u dream-native-inference-worker -f\n'
